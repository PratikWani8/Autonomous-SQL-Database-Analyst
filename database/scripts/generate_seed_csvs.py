def generate():
    os.makedirs("database/seeds", exist_ok=True)
    
    # 1. District Unemployment Stats (PLFS)
    # Generates two reporting periods: 2021-22 and 2022-23
    unemp_file = "database/seeds/district_unemployment_stats.csv"
    with open(unemp_file, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "state_name", "district_name", "reporting_year", 
            "rural_unemployment_rate", "urban_unemployment_rate", "overall_unemployment_rate", 
            "labour_force_participation_rate", "worker_population_ratio", "surveyed_households"
        ])
        for row in DISTRICT_DATA:
            state, district = row[0], row[1]
            ur_21_rural = round(row[6] * 0.95, 2)
            ur_21_urban = round(row[6] * 1.15, 2)
            ur_21_overall = round(row[6], 2)
            lfpr_21 = round(row[8], 2)
            wpr_21 = round(lfpr_21 * (1.0 - ur_21_overall / 100.0), 2)
            households_21 = 450 + (hash(district) % 200)

            # 2021-22
            writer.writerow([
                state, district, "2021-22",
                ur_21_rural, ur_21_urban, ur_21_overall,
                lfpr_21, wpr_21, abs(households_21)
            ])

            # 2022-23
            ur_22_rural = round(row[7] * 0.96, 2)
            ur_22_urban = round(row[7] * 1.14, 2)
            ur_22_overall = round(row[7], 2)
            lfpr_22 = round(row[9], 2)
            wpr_22 = round(lfpr_22 * (1.0 - ur_22_overall / 100.0), 2)
            households_22 = 500 + (hash(district) % 250)
            writer.writerow([
                state, district, "2022-23",
                ur_22_rural, ur_22_urban, ur_22_overall,
                lfpr_22, wpr_22, abs(households_22)
            ])
    print(f"Generated {unemp_file} with {len(DISTRICT_DATA) * 2} rows.")

    # 2. District Demographics Stats (Census 2001 and 2011)
    demo_file = "database/seeds/district_demographics_stats.csv"
    with open(demo_file, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "state_name", "district_name", "census_year",
            "total_population", "male_population", "female_population", "sex_ratio",
            "literacy_rate", "male_literacy_rate", "female_literacy_rate", "area_sq_km"
        ])
        for row in DISTRICT_DATA:
            state, district = row[0], row[1]
            pop_2011 = row[10]
            pop_2001 = row[11]
            sex_ratio_2011 = row[12]
            male_pop_2011 = int(pop_2011 * (1000 / (1000 + sex_ratio_2011)))
            female_pop_2011 = pop_2011 - male_pop_2011
            lit_2011 = row[13]
            m_lit_2011 = row[14]
            f_lit_2011 = row[15]
            area = row[16]

            # 2001 Census
            sex_ratio_2001 = sex_ratio_2011 - 12
            male_pop_2001 = int(pop_2001 * (1000 / (1000 + sex_ratio_2001)))
            female_pop_2001 = pop_2001 - male_pop_2001
            lit_2001 = round(lit_2011 * 0.88, 2)
            m_lit_2001 = round(m_lit_2011 * 0.90, 2)
            f_lit_2001 = round(f_lit_2011 * 0.85, 2)

            writer.writerow([
                state, district, 2001,
                pop_2001, male_pop_2001, female_pop_2001, sex_ratio_2001,
                lit_2001, m_lit_2001, f_lit_2001, area
            ])

            # 2011 Census
            writer.writerow([
                state, district, 2011,
                pop_2011, male_pop_2011, female_pop_2011, sex_ratio_2011,
                lit_2011, m_lit_2011, f_lit_2011, area
            ])
    print(f"Generated {demo_file} with {len(DISTRICT_DATA) * 2} rows.")

    # 3. NFHS-5 Health Indicators (2019-21)
    health_file = "database/seeds/district_health_indicators.csv"
    with open(health_file, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "state_name", "district_name", "survey_period",
            "institutional_births_pct", "children_fully_immunized_pct", "women_literacy_pct",
            "clean_cooking_fuel_pct", "improved_sanitation_pct", "sex_ratio_at_birth"
        ])
        for row in DISTRICT_DATA:
            state, district = row[0], row[1]
            inst_births = row[17]
            immunization = row[18]
            w_lit = row[19]
            clean_fuel = row[20]
            sanitation = row[21]
            srb = row[22]
            writer.writerow([
                state, district, "2019-21",
                inst_births, immunization, w_lit, clean_fuel, sanitation, srb
            ])
    print(f"Generated {health_file} with {len(DISTRICT_DATA)} rows.")

